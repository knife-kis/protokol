    private static int prepareProjectVersion(String projectType, String tableName, int sourceProjectId,
                                             int expectedRevision, String sessionId) throws SQLException {
        if (sourceProjectId <= 0) {
            return 1;
        }
        ProjectLockInfo lockInfo = loadProjectLock(projectType, sourceProjectId, true);
        if (lockInfo == null || sessionId == null || !sessionId.equals(lockInfo.getSessionId())) {
            String owner = lockInfo == null ? "другим пользователем" : lockInfo.getOwnerLabel();
            throw new SQLException("Проект открыт для редактирования " + owner + ". Сохранение отменено.");
        }
        String sql = "SELECT revision FROM " + tableName + " WHERE id=? FOR UPDATE";
        try (PreparedStatement stmt = connection.prepareStatement(sql)) {
            stmt.setInt(1, sourceProjectId);
            try (ResultSet rs = stmt.executeQuery()) {
                if (!rs.next()) {
                    throw new SQLException("Исходная версия проекта больше не существует");
                }
                int actualRevision = rs.getInt("revision");
                if (expectedRevision > 0 && actualRevision != expectedRevision) {
                    throw new SQLException("Версия проекта изменилась после загрузки. Загрузите проект заново.");
                }
                return actualRevision + 1;
            }
        }
    }

