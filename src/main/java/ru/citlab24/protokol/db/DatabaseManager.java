    private static String currentWindowsLogin() throws SQLException {
        String userName = System.getProperty("user.name", "").trim();
        if (userName.isBlank()) {
            throw new SQLException("Не удалось определить текущего пользователя Windows");
        }
        String domain = System.getenv("USERDOMAIN");
        return normalizeWindowsLogin(domain == null || domain.isBlank()
                ? userName
                : domain + "\\" + userName);
    }

    private static String normalizeWindowsLogin(String windowsLogin) throws SQLException {
        String value = windowsLogin == null ? "" : windowsLogin.trim().replace('/', '\\');
        if (value.isBlank()) {
            throw new SQLException("Укажите учётную запись Windows");
        }
        if (value.indexOf('\\') < 0) {
            String domain = System.getenv("USERDOMAIN");
            if (domain != null && !domain.isBlank()) {
                value = domain + "\\" + value;
            }
        }
        return value.toLowerCase(Locale.ROOT);
    }


